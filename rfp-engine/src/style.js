// Voice and style: house rules sent with every drafting prompt, and a checker that flags
// wording that reads as machine-written before anything reaches a customer.

// The style guide itself lives in the team workspace (workspace.js).
const DEFAULT_STYLE = DEFAULT_STYLE_GUIDE;
function styleOf() { return sg(); }
function bannedList() {
  return sg().banned.split(/[,\n]/).map(s => s.trim().toLowerCase()).filter(Boolean);
}

function styleRulesText() {
  const st = sg();
  const terms = terminologyPairs();
  return `HOUSE STYLE GUIDE (mandatory, the text goes to a client and must read as written by our proposal team):
Tone: ${st.tone}
Writing rules:
${st.rules}
${st.formatting ? 'Formatting conventions:\n' + st.formatting : ''}
${terms.length ? 'Terminology (use the first term, never the others):\n' + terms.map(t => `${t.use} (not: ${t.avoid.join(', ')})`).join('\n') : ''}
${st.facts ? 'Approved company facts and figures (use these exact values; never contradict them):\n' + st.facts : ''}
Never use these words or phrases: ${bannedList().join(', ')}.
Do not mention AI, Claude, models, drafts, prompts, the content library, block ids, source systems or this process anywhere in the prose.
${st.voiceSample ? `Match the rhythm and word choice of this sample of our own past writing:\n"""\n${st.voiceSample.slice(0, 2500)}\n"""` : ''}`;
}

/* Checker: returns issues with a short label and the matched text. Runs on plain text. */
function styleIssues(text) {
  const out = [];
  const lower = text.toLowerCase();
  for (const w of bannedList()) {
    const re = new RegExp('(^|[^a-z])' + w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?=$|[^a-z])', 'gi');
    const n = (lower.match(re) || []).length;
    if (n) out.push({ kind: 'banned', label: `"${w}"`, n });
  }
  for (const t of terminologyPairs()) for (const a of t.avoid) {
    const re = new RegExp('(^|[^a-z])' + a.toLowerCase().replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?=$|[^a-z])', 'gi');
    const n = (lower.match(re) || []).length;
    if (n) out.push({ kind: 'term', label: `"${a}" (use "${t.use}")`, n });
  }
  const dashes = (text.match(/[—–]|\s--\s/g) || []).length;
  if (dashes) out.push({ kind: 'dash', label: 'Em or en dash', n: dashes });
  const nb = (text.match(/\bnot only\b[^.]{0,80}\bbut also\b/gi) || []).length;
  if (nb) out.push({ kind: 'pattern', label: '"Not only… but also"', n: nb });
  const q = (text.match(/\?(\s|$)/g) || []).length;
  if (q) out.push({ kind: 'pattern', label: 'Rhetorical question', n: q });
  const ex = (text.match(/!(\s|$)/g) || []).length;
  if (ex) out.push({ kind: 'pattern', label: 'Exclamation mark', n: ex });
  const triads = (text.match(/\b\w+(ly)?,\s\w+,\s(and|or)\s\w+\b/g) || []).length;
  if (triads > 2) out.push({ kind: 'pattern', label: 'Many lists of three', n: triads });
  const sents = text.split(/(?<=[.!?])\s+/).map(s => s.split(/\s+/).length).filter(n => n > 3);
  if (sents.length >= 6) {
    const mean = sents.reduce((a, b) => a + b, 0) / sents.length;
    const sd = Math.sqrt(sents.reduce((a, b) => a + (b - mean) ** 2, 0) / sents.length);
    if (sd / mean < 0.28) out.push({ kind: 'rhythm', label: 'Sentence lengths too uniform', n: 1 });
  }
  if (/\b(as an ai|language model|claude|chatgpt|generated by|this draft)\b/i.test(text)) out.push({ kind: 'leak', label: 'Mentions AI or drafting', n: 1 });
  if (/\b(B-\d{3}|R-\d{3}|A-\d{3})\b/.test(text) || /\b(glean|salesforce|slack|confluence)\b/i.test(text)) out.push({ kind: 'leak', label: 'Internal id in text', n: 1 });
  return out;
}
function blockText(b) {
  if (b.type === 'text' || b.type === 'callout') return htmlToText(b.html);
  if (b.type === 'image') return b.caption || '';
  if (b.type === 'table') return (b.rows || []).map(r => r.join(' ')).join('\n') + ' ' + (b.caption || '');
  return '';
}
function sectionStyleIssues(sec) {
  const all = [];
  for (const b of sec.blocks) {
    if (b.mode === 'verbatim') continue; // approved library text is the team's own writing
    for (const i of styleIssues(blockText(b))) all.push(Object.assign({ blockId: b.id }, i));
  }
  return all;
}
function projectStyleIssues() {
  return S.project.sections.map(s => ({ sec: s, issues: sectionStyleIssues(s) })).filter(x => x.issues.length);
}

/* Deterministic clean-up for the mechanical tells: dashes become commas, and stray spacing is fixed. */
function autoFixText(html) {
  return html
    .replace(/\s*[—]\s*/g, ', ')
    .replace(/(\d)\s*[–]\s*(\d)/g, '$1 to $2')
    .replace(/\s*[–]\s*/g, ', ')
    .replace(/\s--\s/g, ', ')
    .replace(/,\s*,/g, ',')
    .replace(/!(\s|<|$)/g, '.$1');
}

function promptRestyle(p, sec, items) {
  return `Rewrite these passages from section "${sec.title}" of an RFP response so they read as written by an experienced human proposal writer. Keep every fact, number, name and every [NEEDS INPUT: ...] and [CONFIRM: ...] marker exactly. Apply the terminology list. Do not add new claims. Keep the same HTML tags (<p>, <ul>, <li>, <b>, <i>).

${styleRulesText(p)}

Problems found by the style checker: ${items.map(i => i.issues.map(x => x.label).join(', ')).join(' | ')}

Passages:
${items.map(i => `### ${i.id}\n${i.html}`).join('\n\n')}

Return JSON: {"items":[{"id":"...","html":"..."}]}`;
}

async function restyleSection(sec) {
  const p = S.project;
  const targets = sec.blocks.filter(b => (b.type === 'text' || b.type === 'callout') && b.mode !== 'verbatim' && !b.locked)
    .map(b => ({ id: b.id, html: b.html, issues: styleIssues(htmlToText(b.html)) }))
    .filter(t => t.issues.length);
  if (!targets.length) { toast('No style issues in unlocked blocks of this section.'); return; }
  for (const t of targets) { const b = sec.blocks.find(x => x.id === t.id); b.html = autoFixText(b.html); t.html = b.html; t.issues = styleIssues(htmlToText(b.html)); }
  const still = targets.filter(t => t.issues.length);
  if (still.length && AI.sample) {
    const res = await askJSON(promptRestyle(p, sec, still), { label: `Rewriting flagged passages in ${sec.num}` });
    for (const it of (res && res.items) || []) {
      const b = sec.blocks.find(x => x.id === it.id);
      if (b && it.html) b.html = autoFixText(sanitize(it.html));
    }
  }
  logChange('engine', `Style pass on ${sec.num} ${sec.title}: ${targets.length} block(s) rewritten.`);
  save();
}
